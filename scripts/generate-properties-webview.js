#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const repositoryRoot = path.resolve(__dirname, '..');
const outputPath = path.join(
  repositoryRoot,
  'src',
  'providers',
  'propertiesWebview',
  'generatedAssets.ts',
);
const browserRoot = path.join(repositoryRoot, 'src', 'providers', 'propertiesWebview', 'browser');
const styleRoot = path.join(repositoryRoot, 'src', 'providers', 'propertiesWebview', 'styles');

function bundle(entryPoint) {
  const result = esbuild.buildSync({
    absWorkingDir: repositoryRoot,
    entryPoints: [path.join(browserRoot, entryPoint)],
    bundle: true,
    platform: 'browser',
    format: 'iife',
    target: 'es2020',
    minifyWhitespace: true,
    legalComments: 'none',
    write: false,
  });
  return result.outputFiles[0].text.replace(/\r\n/g, '\n').trimEnd();
}

function readStyle(fileName) {
  return fs.readFileSync(path.join(styleRoot, fileName), 'utf8').replace(/\r\n/g, '\n');
}

function createArtifact() {
  const assets = [
    ['PROPERTIES_CSS', readStyle('metadata.css')],
    ['EMPTY_STATE_CSS', readStyle('empty.css')],
    ['ERROR_PANEL_CSS', readStyle('error.css')],
    ['FORM_SELECTION_CSS', readStyle('formSelection.css')],
    ['PROPERTIES_BROWSER_SCRIPT', bundle('propertiesEntry.ts')],
    ['FORM_SELECTION_BROWSER_SCRIPT', bundle('formSelectionEntry.ts')],
  ];
  return [
    '/* Generated by scripts/generate-properties-webview.js; edit browser/ and styles/ sources instead. */',
    ...assets.map(([name, value]) => 'export const ' + name + ' = ' + JSON.stringify(value) + ';'),
    '',
  ].join('\n');
}

function main() {
  const checkOnly = process.argv.includes('--check');
  const unknownArgs = process.argv.slice(2).filter((arg) => arg !== '--check');
  if (unknownArgs.length > 0) {
    console.error('Usage: node scripts/generate-properties-webview.js [--check]');
    process.exit(2);
  }

  const expected = createArtifact();
  if (checkOnly) {
    if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== expected) {
      console.error('Generated Properties Webview assets are stale. Run npm run generate:properties-webview.');
      process.exit(1);
    }
    console.log('Generated Properties Webview assets are current.');
    return;
  }

  fs.writeFileSync(outputPath, expected, 'utf8');
  console.log('Generated ' + path.relative(repositoryRoot, outputPath) + '.');
}

main();
