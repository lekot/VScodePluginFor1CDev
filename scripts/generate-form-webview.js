#!/usr/bin/env node
'use strict';

const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const repositoryRoot = path.resolve(__dirname, '..');
const webviewRoot = path.join(repositoryRoot, 'src', 'formEditor', 'formWebview');
const browserRoot = path.join(webviewRoot, 'browser');
const outputPath = path.join(webviewRoot, 'generatedAssets.ts');

function normalizeLineEndings(value) {
  return value.replace(/\r\n/g, '\n');
}

function bundleBrowserApplication() {
  const result = esbuild.buildSync({
    absWorkingDir: repositoryRoot,
    entryPoints: [path.join(browserRoot, 'entry.ts')],
    bundle: true,
    platform: 'browser',
    format: 'iife',
    target: 'es2020',
    minifyWhitespace: true,
    legalComments: 'none',
    sourcemap: 'inline',
    sourcesContent: true,
    outfile: path.join('out', 'form-webview-runtime.generated.js'),
    write: false,
  });
  return normalizeLineEndings(result.outputFiles[0].text).trimEnd();
}

function serialize(value) {
  return JSON.stringify(value).replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
}

function createArtifact() {
  const css = normalizeLineEndings(fs.readFileSync(path.join(webviewRoot, 'styles', 'editor.css'), 'utf8'));
  const script = bundleBrowserApplication();
  return [
    '// Generated by scripts/generate-form-webview.js. Do not edit by hand.',
    `export const FORM_WEBVIEW_CSS = ${serialize(css)};`,
    `export const FORM_WEBVIEW_SCRIPT = ${serialize(script)};`,
    '',
  ].join('\n');
}

const expected = createArtifact();
const checkOnly = process.argv.includes('--check');
if (checkOnly) {
  const current = fs.existsSync(outputPath) ? normalizeLineEndings(fs.readFileSync(outputPath, 'utf8')) : '';
  if (current !== expected) {
    console.error('Form webview generated assets are stale. Run npm run generate:form-webview.');
    process.exitCode = 1;
  }
} else {
  fs.writeFileSync(outputPath, expected, 'utf8');
}
